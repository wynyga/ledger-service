-- Double-entry ledger. Amounts are bigint minor units.

create table accounts (
    id             uuid primary key,
    currency       varchar(3)  not null,
    balance        bigint      not null,
    allow_negative boolean     not null default false,
    status         varchar(16) not null,
    -- Set only on system accounts, e.g. FUNDING_IDR.
    system_code    varchar(32) unique,
    created_at     timestamptz not null,
    -- Last line of defence: the domain already refuses this.
    constraint chk_accounts_balance check (allow_negative or balance >= 0)
);

create table transfers (
    id                uuid primary key,
    idempotency_key   varchar(100) not null constraint uq_transfers_idempotency_key unique,
    request_hash      varchar(64)  not null,
    type              varchar(16)  not null,
    debit_account_id  uuid         not null references accounts (id),
    credit_account_id uuid         not null references accounts (id),
    amount            bigint       not null check (amount > 0),
    currency          varchar(3)   not null,
    created_at        timestamptz  not null,
    check (debit_account_id <> credit_account_id)
);

create table entries (
    id            bigint generated by default as identity primary key,
    transfer_id   uuid        not null references transfers (id),
    account_id    uuid        not null references accounts (id),
    direction     varchar(6)  not null check (direction in ('DEBIT', 'CREDIT')),
    amount        bigint      not null check (amount > 0),
    balance_after bigint      not null,
    created_at    timestamptz not null
);

create index ix_entries_account on entries (account_id, id desc);
create index ix_entries_transfer on entries (transfer_id);
create index ix_transfers_debit on transfers (debit_account_id);
create index ix_transfers_credit on transfers (credit_account_id);

-- History is never rewritten: corrections are new transfers.
create function ledger_append_only() returns trigger
    language plpgsql as
$$
begin
    raise exception '% is append-only', tg_table_name;
end;
$$;

create trigger entries_append_only
    before update or delete on entries
    for each row execute function ledger_append_only();

create trigger transfers_append_only
    before update or delete on transfers
    for each row execute function ledger_append_only();

